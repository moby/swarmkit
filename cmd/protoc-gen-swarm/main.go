// Command protoc-gen-swarm generates the swarmkit-specific helpers that no
// upstream protoc plugin provides: object Copy methods, the store object and
// event plumbing, raft leader proxies and authenticated service wrappers.
//
// Message and enum types, gRPC stubs and the fast marshallers come from
// protoc-gen-go, protoc-gen-go-grpc and protoc-gen-go-vtproto respectively.
package main

import (
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/moby/swarmkit/v2/protobuf/plugin/authenticatedwrapper"
	"github.com/moby/swarmkit/v2/protobuf/plugin/deepcopy"
	"github.com/moby/swarmkit/v2/protobuf/plugin/raftproxy"
	"github.com/moby/swarmkit/v2/protobuf/plugin/storeobject"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range gen.Files {
			if f.Generate {
				generateFile(gen, f)
			}
		}
		return nil
	})
}

func generateFile(gen *protogen.Plugin, f *protogen.File) {
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+"_swarm.pb.go", f.GoImportPath)
	g.P("// Code generated by protoc-gen-swarm. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()

	deepcopy.Generate(g, f)
	storeobject.Generate(g, f)
	raftproxy.Generate(g, f)
	authenticatedwrapper.Generate(g, f)
}
