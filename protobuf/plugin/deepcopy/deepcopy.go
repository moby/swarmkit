// Package deepcopy is a protoc-gen-goswarm plugin that generates Copy() and
// CopyFrom() methods for every proto message.
package deepcopy

import (
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"

	pluginpb "github.com/moby/swarmkit/v2/protobuf/plugin"
	"github.com/moby/swarmkit/v2/protobuf/plugin/naming"
)

const deepcopyPkg = "github.com/moby/swarmkit/v2/api/deepcopy"

// Generate writes deepcopy methods for all eligible messages in f into a
// separate <basename>.pb.deepcopy.go file.
func Generate(gen *protogen.Plugin, f *protogen.File) {
	var msgs []*protogen.Message
	for _, m := range f.Messages {
		if eligibleMessages(m) != nil {
			msgs = append(msgs, eligibleMessages(m)...)
		}
	}
	if len(msgs) == 0 {
		return
	}

	out := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+".pb.deepcopy.go", f.GoImportPath)
	out.P("// Code generated by protoc-gen-goswarm. DO NOT EDIT.")
	out.P()
	out.P("package ", f.GoPackageName)
	out.P()

	for _, m := range msgs {
		genMsgDeepCopy(out, m)
	}
}

// eligibleMessages returns all non-map messages in m (recursively) where
// deepcopy is enabled (the default is true).
func eligibleMessages(m *protogen.Message) []*protogen.Message {
	if m.Desc.IsMapEntry() {
		return nil
	}
	var result []*protogen.Message
	if deepcopyEnabled(m) {
		result = append(result, m)
	}
	for _, nested := range m.Messages {
		result = append(result, eligibleMessages(nested)...)
	}
	return result
}

func deepcopyEnabled(m *protogen.Message) bool {
	opts := m.Desc.Options()
	if opts == nil {
		return true
	}
	if !proto.HasExtension(opts, pluginpb.E_Deepcopy) {
		return true
	}
	v := proto.GetExtension(opts, pluginpb.E_Deepcopy)
	if b, ok := v.(bool); ok {
		return b
	}
	if b, ok := v.(*bool); ok && b != nil {
		return *b
	}
	return true
}

func genMsgDeepCopy(g *protogen.GeneratedFile, m *protogen.Message) {
	typeName := m.GoIdent.GoName

	// Copy() method
	g.P("func (m *", typeName, ") Copy() *", typeName, " {")
	g.P("if m == nil {")
	g.P("return nil")
	g.P("}")
	g.P("o := &", typeName, "{}")
	g.P("o.CopyFrom(m)")
	g.P("return o")
	g.P("}")
	g.P()

	if len(m.Fields) == 0 {
		g.P("func (m *", typeName, ") CopyFrom(src interface{}) {}")
		g.P()
		return
	}

	// CopyFrom() method.
	//
	// NB: we deliberately do NOT use `*m = *o` to bulk-copy scalars. The
	// generated structs embed protoimpl.MessageState (which contains a
	// sync.Mutex), so a whole-struct copy would copy a lock and trip
	// `go vet`'s copylocks check. Instead each field is copied explicitly,
	// leaving the embedded state/unknownFields/sizeCache untouched.
	g.P("func (m *", typeName, ") CopyFrom(src interface{}) {")
	g.P()
	g.P("o := src.(*", typeName, ")")

	// Track which fields belong to each oneof (by oneof index)
	oneofFields := map[int][]*protogen.Field{}
	for _, f := range m.Fields {
		if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
			idx := f.Oneof.Desc.Index()
			oneofFields[idx] = append(oneofFields[idx], f)
		}
	}

	// Emit copy logic for non-oneof fields.
	for _, f := range m.Fields {
		// Skip oneof wrapper fields (handled separately)
		if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
			continue
		}

		if f.Desc.IsMap() {
			genMapField(g, m, f)
		} else if f.Message != nil && f.Desc.IsList() {
			genRepeatedMessageField(g, f)
		} else if f.Enum == nil && f.Message != nil {
			// Single message field (always a pointer in standard proto)
			genNullableMessageField(g, f)
		} else if f.Desc.IsList() {
			if f.Desc.Kind() == protoreflect.BytesKind {
				genRepeatedBytesField(g, f)
			} else {
				genRepeatedScalarField(g, f)
			}
		} else if f.Desc.Kind() == protoreflect.BytesKind {
			genBytesField(g, f)
		} else {
			// Scalar or enum field: copy by value. For proto3-optional
			// (synthetic oneof) fields the Go type is a pointer; copying the
			// pointer matches the previous whole-struct-copy behaviour.
			fName := fieldGoName(f)
			g.P("m.", fName, " = o.", fName)
		}
	}

	// Emit oneof copy logic
	for idx := range oneofFields {
		// Find the Oneof from any field in this group
		oneof := oneofFields[idx][0].Oneof
		genOneofFields(g, m, oneof, oneofFields[idx])
	}

	g.P("}")
	g.P()
}

func fieldGoName(f *protogen.Field) string {
	return naming.GoFieldName(f)
}

func genNullableMessageField(g *protogen.GeneratedFile, f *protogen.Field) {
	fName := fieldGoName(f)
	msgTypeName := f.Message.GoIdent
	g.P("if o.", fName, " != nil {")
	g.P("m.", fName, " = &", g.QualifiedGoIdent(msgTypeName), "{}")
	g.P(g.QualifiedGoIdent(protogen.GoIdent{GoName: "Copy", GoImportPath: deepcopyPkg}), "(m.", fName, ", o.", fName, ")")
	g.P("}")
	g.P()
}

func genBytesField(g *protogen.GeneratedFile, f *protogen.Field) {
	fName := fieldGoName(f)
	g.P("if o.", fName, " != nil {")
	g.P("m.", fName, " = make([]byte, len(o.", fName, "))")
	g.P("copy(m.", fName, ", o.", fName, ")")
	g.P("}")
	g.P()
}

func genRepeatedMessageField(g *protogen.GeneratedFile, f *protogen.Field) {
	fName := fieldGoName(f)
	msgTypeName := f.Message.GoIdent
	g.P("if o.", fName, " != nil {")
	g.P("m.", fName, " = make([]*", g.QualifiedGoIdent(msgTypeName), ", len(o.", fName, "))")
	g.P("for i := range m.", fName, " {")
	g.P("m.", fName, "[i] = &", g.QualifiedGoIdent(msgTypeName), "{}")
	g.P(g.QualifiedGoIdent(protogen.GoIdent{GoName: "Copy", GoImportPath: deepcopyPkg}), "(m.", fName, "[i], o.", fName, "[i])")
	g.P("}")
	g.P("}")
	g.P()
}

func genRepeatedBytesField(g *protogen.GeneratedFile, f *protogen.Field) {
	fName := fieldGoName(f)
	g.P("if o.", fName, " != nil {")
	g.P("m.", fName, " = make([][]byte, len(o.", fName, "))")
	g.P("for i := range m.", fName, " {")
	g.P("if o.", fName, "[i] != nil {")
	g.P("m.", fName, "[i] = make([]byte, len(o.", fName, "[i]))")
	g.P("copy(m.", fName, "[i], o.", fName, "[i])")
	g.P("}")
	g.P("}")
	g.P("}")
	g.P()
}

func genRepeatedScalarField(g *protogen.GeneratedFile, f *protogen.Field) {
	fName := fieldGoName(f)
	g.P("if o.", fName, " != nil {")
	g.P("m.", fName, " = make(", sliceType(g, f), ", len(o.", fName, "))")
	g.P("copy(m.", fName, ", o.", fName, ")")
	g.P("}")
	g.P()
}

func sliceType(g *protogen.GeneratedFile, f *protogen.Field) string {
	if f.Enum != nil {
		return "[]" + g.QualifiedGoIdent(f.Enum.GoIdent)
	}
	switch f.Desc.Kind() {
	case protoreflect.BoolKind:
		return "[]bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "[]int32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "[]uint32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "[]int64"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "[]uint64"
	case protoreflect.FloatKind:
		return "[]float32"
	case protoreflect.DoubleKind:
		return "[]float64"
	case protoreflect.StringKind:
		return "[]string"
	default:
		return "[]interface{}"
	}
}

func genMapField(g *protogen.GeneratedFile, m *protogen.Message, f *protogen.Field) {
	fName := fieldGoName(f)

	// Find the map entry message
	mapEntry := f.Message
	keyField := mapEntry.Fields[0]
	valField := mapEntry.Fields[1]

	keyType := mapKeyType(g, keyField)
	valType := mapValueType(g, valField)

	g.P("if o.", fName, " != nil {")
	g.P("m.", fName, " = make(map[", keyType, "]", valType, ", len(o.", fName, "))")
	g.P("for k, v := range o.", fName, " {")
	if valField.Message != nil {
		// Map with message value
		valGoName := g.QualifiedGoIdent(valField.Message.GoIdent)
		g.P("m.", fName, "[k] = &", valGoName, "{}")
		g.P(g.QualifiedGoIdent(protogen.GoIdent{GoName: "Copy", GoImportPath: deepcopyPkg}), "(m.", fName, "[k], v)")
	} else if valField.Desc.Kind() == protoreflect.BytesKind {
		g.P("if v != nil {")
		g.P("mv := make([]byte, len(v))")
		g.P("copy(mv, v)")
		g.P("m.", fName, "[k] = mv")
		g.P("} else {")
		g.P("m.", fName, "[k] = nil")
		g.P("}")
	} else {
		g.P("m.", fName, "[k] = v")
	}
	g.P("}")
	g.P("}")
	g.P()

	_ = m
}

func mapKeyType(g *protogen.GeneratedFile, f *protogen.Field) string {
	switch f.Desc.Kind() {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	default:
		return "interface{}"
	}
}

func mapValueType(g *protogen.GeneratedFile, f *protogen.Field) string {
	if f.Message != nil {
		return "*" + g.QualifiedGoIdent(f.Message.GoIdent)
	}
	switch f.Desc.Kind() {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.BytesKind:
		return "[]byte"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float32"
	case protoreflect.DoubleKind:
		return "float64"
	default:
		return "interface{}"
	}
}

func genOneofFields(g *protogen.GeneratedFile, m *protogen.Message, oneof *protogen.Oneof, fields []*protogen.Field) {
	oneofGoName := oneof.GoName
	msgTypeName := m.GoIdent.GoName

	g.P("if o.", oneofGoName, " != nil {")
	g.P("switch o.", oneofGoName, ".(type) {")

	for _, f := range fields {
		fGoName := fieldGoName(f)
		wrapperTypeName := msgTypeName + "_" + fGoName
		g.P("case *", wrapperTypeName, ":")

		if f.Message != nil {
			innerTypeName := g.QualifiedGoIdent(f.Message.GoIdent)
			g.P("v := ", wrapperTypeName, "{")
			g.P(fGoName, ": &", innerTypeName, "{},")
			g.P("}")
			// v.fGoName is already *Message; pass directly (not &v.fGoName which would be **)
			g.P(g.QualifiedGoIdent(protogen.GoIdent{GoName: "Copy", GoImportPath: deepcopyPkg}), "(v.", fGoName, ", o.Get", fGoName, "())")
			g.P("m.", oneofGoName, " = &v")
		} else if f.Desc.Kind() == protoreflect.BytesKind {
			g.P("v := ", wrapperTypeName, "{")
			g.P(fGoName, ": make([]byte, len(o.Get", fGoName, "())),")
			g.P("}")
			g.P("copy(v.", fGoName, ", o.Get", fGoName, "())")
			g.P("m.", oneofGoName, " = &v")
		} else {
			g.P("v := ", wrapperTypeName, "{", fGoName, ": o.Get", fGoName, "()}")
			g.P("m.", oneofGoName, " = &v")
		}
	}

	g.P("}")
	g.P("}")
	g.P()
}
