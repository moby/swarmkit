// Package raftproxy is a protoc-gen-goswarm plugin that generates
// Raft-leader-aware gRPC server proxy wrappers.
package raftproxy

import (
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// Generate writes raftproxy server wrappers for all services in f.
func Generate(gen *protogen.Plugin, f *protogen.File) {
	if len(f.Services) == 0 {
		return
	}

	out := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+".pb.raftproxy.go", f.GoImportPath)
	out.P("// Code generated by protoc-gen-goswarm. DO NOT EDIT.")
	out.P()
	out.P("package ", f.GoPackageName)
	out.P()

	// Trigger import of required packages.
	// Always-needed imports
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "Context", GoImportPath: "context"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "ConnProvider", GoImportPath: "github.com/moby/swarmkit/v2/manager/raftselector"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "InvalidArgument", GoImportPath: "google.golang.org/grpc/codes"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "Errorf", GoImportPath: "google.golang.org/grpc/status"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "FromIncomingContext", GoImportPath: "google.golang.org/grpc/metadata"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "FromContext", GoImportPath: "google.golang.org/grpc/peer"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "ClientConn", GoImportPath: "google.golang.org/grpc"})
	_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "NewTicker", GoImportPath: "time"})

	// Conditionally import io (needed for streaming) and strings (needed for unary)
	hasStreaming := false
	hasUnary := false
	for _, s := range f.Services {
		for _, m := range s.Methods {
			if m.Desc.IsStreamingServer() || m.Desc.IsStreamingClient() {
				hasStreaming = true
			} else {
				hasUnary = true
			}
		}
	}
	if hasStreaming {
		_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "EOF", GoImportPath: "io"})
	}
	if hasUnary {
		_ = out.QualifiedGoIdent(protogen.GoIdent{GoName: "Contains", GoImportPath: "strings"})
	}

	for _, s := range f.Services {
		genProxyService(out, s)
	}
}

func serviceTypeName(s *protogen.Service) string {
	return "raftProxy" + s.GoName + "Server"
}

func genProxyService(g *protogen.GeneratedFile, s *protogen.Service) {
	g.P()
	genProxyStruct(g, s)
	genProxyConstructor(g, s)
	genRunCtxMods(g, s)
	genPollNewLeaderConn(g, s)
	for _, m := range s.Methods {
		genProxyMethod(g, s, m)
	}
	g.P()
}

func genProxyStruct(g *protogen.GeneratedFile, s *protogen.Service) {
	g.P("type " + serviceTypeName(s) + " struct {")
	g.P("\tlocal " + s.GoName + "Server")
	g.P("\tconnSelector raftselector.ConnProvider")
	g.P("\tlocalCtxMods, remoteCtxMods []func(context.Context)(context.Context, error)")
	g.P("}")
}

func genProxyConstructor(g *protogen.GeneratedFile, s *protogen.Service) {
	g.P("func NewRaftProxy" + s.GoName + "Server(local " + s.GoName + "Server, connSelector raftselector.ConnProvider, localCtxMod, remoteCtxMod func(context.Context)(context.Context, error)) " + s.GoName + "Server {")
	g.P(`redirectChecker := func(ctx context.Context)(context.Context, error) {
	p, ok := peer.FromContext(ctx)
	if !ok {
		return ctx, status.Errorf(codes.InvalidArgument, "remote addr is not found in context")
	}
	addr := p.Addr.String()
	md, ok := metadata.FromIncomingContext(ctx)
	if ok && len(md["redirect"]) != 0 {
		return ctx, status.Errorf(codes.ResourceExhausted, "more than one redirect to leader from: %s", md["redirect"])
	}
	if !ok {
		md = metadata.New(map[string]string{})
	}
	md["redirect"] = append(md["redirect"], addr)
	return metadata.NewOutgoingContext(ctx, md), nil
}
remoteMods := []func(context.Context)(context.Context, error){redirectChecker}
remoteMods = append(remoteMods, remoteCtxMod)

var localMods []func(context.Context)(context.Context, error)
if localCtxMod != nil {
	localMods = []func(context.Context)(context.Context, error){localCtxMod}
}
`)
	g.P("return &" + serviceTypeName(s) + `{
	local: local,
	connSelector: connSelector,
	localCtxMods: localMods,
	remoteCtxMods: remoteMods,
}`)
	g.P("}")
}

func genRunCtxMods(g *protogen.GeneratedFile, s *protogen.Service) {
	g.P("func (p *" + serviceTypeName(s) + `) runCtxMods(ctx context.Context, ctxMods []func(context.Context)(context.Context, error)) (context.Context, error) {
	var err error
	for _, mod := range ctxMods {
		ctx, err = mod(ctx)
		if err != nil {
			return ctx, err
		}
	}
	return ctx, nil
}`)
}

func genPollNewLeaderConn(g *protogen.GeneratedFile, s *protogen.Service) {
	g.P(`func (p *` + serviceTypeName(s) + `) pollNewLeaderConn(ctx context.Context) (*grpc.ClientConn, error) {
	ticker := time.NewTicker(500 * time.Millisecond)
	defer ticker.Stop()
	for {
		select {
		case <-ticker.C:
			conn, err := p.connSelector.LeaderConn(ctx)
			if err != nil {
				return nil, err
			}

			client := NewHealthClient(conn)

			resp, err := client.Check(ctx, &HealthCheckRequest{Service: "Raft"})
			if err != nil || resp.Status != HealthCheckResponse_SERVING {
				continue
			}
			return conn, nil
		case <-ctx.Done():
			return nil, ctx.Err()
		}
	}
}`)
}

func genProxyMethod(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	g.P()
	switch {
	case m.Desc.IsStreamingServer() && m.Desc.IsStreamingClient():
		genClientServerStreamingMethod(g, s, m)
	case m.Desc.IsStreamingServer():
		genServerStreamingMethod(g, s, m)
	case m.Desc.IsStreamingClient():
		genClientStreamingMethod(g, s, m)
	default:
		genSimpleMethod(g, s, m)
	}
	g.P()
}

func inputTypeName(m *protogen.Method) string {
	return m.Input.GoIdent.GoName
}

func outputTypeName(m *protogen.Method) string {
	return m.Output.GoIdent.GoName
}

func sigPrefix(s *protogen.Service, m *protogen.Method) string {
	return "func (p *" + serviceTypeName(s) + ") " + m.GoName + "("
}

func streamTypeName(s *protogen.Service, m *protogen.Method) string {
	return s.GoName + "_" + m.GoName + "Server"
}

func genStreamWrapper(g *protogen.GeneratedFile, streamType string) {
	g.P("type " + streamType + `Wrapper struct {
	` + streamType + `
	ctx context.Context
}
`)
	g.P("func (s " + streamType + `Wrapper) Context() context.Context {
	return s.ctx
}
`)
}

func genSimpleMethod(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	inType := inputTypeName(m)
	outType := outputTypeName(m)
	g.P(sigPrefix(s, m) + "ctx context.Context, r *" + inType + ") (*" + outType + ", error) {")
	g.P(`
	conn, err := p.connSelector.LeaderConn(ctx)
	if err != nil {
		if err == raftselector.ErrIsLeader {
			ctx, err = p.runCtxMods(ctx, p.localCtxMods)
			if err != nil {
				return nil, err
			}
			return p.local.` + m.GoName + `(ctx, r)
		}
		return nil, err
	}
	modCtx, err := p.runCtxMods(ctx, p.remoteCtxMods)
	if err != nil {
		return nil, err
	}`)
	g.P(`
	resp, err := New` + s.GoName + `Client(conn).` + m.GoName + `(modCtx, r)
	if err != nil {
		if !strings.Contains(err.Error(), "is closing") && !strings.Contains(err.Error(), "the connection is unavailable") && !strings.Contains(err.Error(), "connection error") {
			return resp, err
		}
		conn, err := p.pollNewLeaderConn(ctx)
		if err != nil {
			if err == raftselector.ErrIsLeader {
				return p.local.` + m.GoName + `(ctx, r)
			}
			return nil, err
		}
		return New` + s.GoName + `Client(conn).` + m.GoName + `(modCtx, r)
	}`)
	g.P("return resp, err")
	g.P("}")
}

func genClientStreamingMethod(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	streamType := streamTypeName(s, m)
	genStreamWrapper(g, streamType)

	g.P(sigPrefix(s, m) + "stream " + streamType + `) error {
	ctx := stream.Context()
	conn, err := p.connSelector.LeaderConn(ctx)
	if err != nil {
		if err == raftselector.ErrIsLeader {
			ctx, err = p.runCtxMods(ctx, p.localCtxMods)
			if err != nil {
				return err
			}
			streamWrapper := ` + streamType + `Wrapper{
				` + streamType + `: stream,
				ctx: ctx,
			}
			return p.local.` + m.GoName + `(streamWrapper)
		}
		return err
	}
	ctx, err = p.runCtxMods(ctx, p.remoteCtxMods)
	if err != nil {
		return err
	}`)
	g.P("clientStream, err := New" + s.GoName + "Client(conn)." + m.GoName + "(ctx)")
	g.P(`
	if err != nil {
		return err
	}`)
	g.P(`
	for {
		msg, err := stream.Recv()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		if err := clientStream.Send(msg); err != nil {
			return err
		}
	}

	reply, err := clientStream.CloseAndRecv()
	if err != nil {
		return err
	}

	return stream.SendAndClose(reply)`)
	g.P("}")
}

func genServerStreamingMethod(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	streamType := streamTypeName(s, m)
	inType := inputTypeName(m)
	genStreamWrapper(g, streamType)

	g.P(sigPrefix(s, m) + "r *" + inType + ", stream " + streamType + `) error {
	ctx := stream.Context()
	conn, err := p.connSelector.LeaderConn(ctx)
	if err != nil {
		if err == raftselector.ErrIsLeader {
			ctx, err = p.runCtxMods(ctx, p.localCtxMods)
			if err != nil {
				return err
			}
			streamWrapper := ` + streamType + `Wrapper{
				` + streamType + `: stream,
				ctx: ctx,
			}
			return p.local.` + m.GoName + `(r, streamWrapper)
		}
		return err
	}
	ctx, err = p.runCtxMods(ctx, p.remoteCtxMods)
	if err != nil {
		return err
	}`)
	g.P("clientStream, err := New" + s.GoName + "Client(conn)." + m.GoName + "(ctx, r)")
	g.P(`
	if err != nil {
		return err
	}`)
	g.P(`
	for {
		msg, err := clientStream.Recv()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		if err := stream.Send(msg); err != nil {
			return err
		}
	}
	return nil`)
	g.P("}")
}

func genClientServerStreamingMethod(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	streamType := streamTypeName(s, m)
	genStreamWrapper(g, streamType)

	g.P(sigPrefix(s, m) + "stream " + streamType + `) error {
	ctx := stream.Context()
	conn, err := p.connSelector.LeaderConn(ctx)
	if err != nil {
		if err == raftselector.ErrIsLeader {
			ctx, err = p.runCtxMods(ctx, p.localCtxMods)
			if err != nil {
				return err
			}
			streamWrapper := ` + streamType + `Wrapper{
				` + streamType + `: stream,
				ctx: ctx,
			}
			return p.local.` + m.GoName + `(streamWrapper)
		}
		return err
	}
	ctx, err = p.runCtxMods(ctx, p.remoteCtxMods)
	if err != nil {
		return err
	}`)
	g.P("clientStream, err := New" + s.GoName + "Client(conn)." + m.GoName + "(ctx)")
	g.P(`
	if err != nil {
		return err
	}`)
	g.P(`errc := make(chan error, 1)
	go func() {
		msg, err := stream.Recv()
		if err == io.EOF {
			close(errc)
			return
		}
		if err != nil {
			errc <- err
			return
		}
		if err := clientStream.Send(msg); err != nil {
			errc <- err
			return
		}
	}()`)
	g.P(`
	for {
		msg, err := clientStream.Recv()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		if err := stream.Send(msg); err != nil {
			return err
		}
	}
	clientStream.CloseSend()
	return <-errc`)
	g.P("}")
}

